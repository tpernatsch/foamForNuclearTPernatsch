def _unified_diff(old: str, new: str, filename: str) -> str:
    """Return a unified diff string between old and new yaml content."""
    lines = list(difflib.unified_diff(
        old.splitlines(keepends=True),
        new.splitlines(keepends=True),
        fromfile=f"{filename} (original)",
        tofile=f"{filename} (proposed)",
        n=3,
    ))
    return "".join(lines)


def _diff_size(old: str, new: str) -> int:
    """Number of changed lines between old and new."""
    matcher = difflib.SequenceMatcher(None, old.splitlines(), new.splitlines())
    return sum(max(j2 - j1, i2 - i1) for _, i1, i2, j1, j2 in matcher.get_opcodes() if _ != "equal")


def print_dry_run_report(all_results: list[dict], repo_root: Path) -> None:
    """
    Print a human-readable dry-run report:
    - A few newly generated yaml files shown in full
    - Modified files shown as diffs, ranked by change size
      (1 minimal change, 2 heavy changes highlighted)
    """
    SEP = "─" * 72

    generated = [r for r in all_results if r.get("action") == "generated" and "new_content" in r]
    modified  = [r for r in all_results
                 if r.get("action", "") not in ("none", "generated")
                 and "new_content" in r]

    print()
    print("=" * 72)
    print("DRY-RUN REPORT")
    print("=" * 72)
    print(f"  Files that would be generated : {len(generated)}")
    print(f"  Files that would be modified  : {len(modified)}")
    print()

    # ---- Generated files: show up to 3 examples in full --------------------
    if generated:
        print(SEP)
        print("GENERATED (sample — up to 3 files shown in full)")
        print(SEP)
        for r in generated[:3]:
            name = Path(r["path"]).relative_to(repo_root)
            print(f"\n### {name}\n")
            print(r["new_content"])
            print()

        if len(generated) > 3:
            remaining = [str(Path(r["path"]).relative_to(repo_root)) for r in generated[3:]]
            print(f"  ... and {len(remaining)} more:")
            for p in remaining:
                print(f"    {p}")
        print()

    # ---- Modified files: rank by diff size, show 1 minimal + 2 heavy ------
    if modified:
        # Attach diff size and diff text to each result
        enriched = []
        for r in modified:
            original = Path(r["path"]).read_text(encoding="utf-8")
            diff_text = _unified_diff(original, r["new_content"], Path(r["path"]).name)
            size = _diff_size(original, r["new_content"])
            enriched.append((size, diff_text, r))

        enriched.sort(key=lambda x: x[0])  # ascending: smallest change first

        # Pick examples: 1 minimal, 2 heaviest
        to_show: list[tuple] = []
        if len(enriched) >= 1:
            to_show.append(("MINIMAL CHANGE", enriched[0]))
        if len(enriched) >= 2:
            to_show.append(("HEAVY CHANGE (1)", enriched[-1]))
        if len(enriched) >= 3:
            to_show.append(("HEAVY CHANGE (2)", enriched[-2]))

        print(SEP)
        print("MODIFIED FILES (sample — ranked by change size)")
        print(SEP)

        for label, (size, diff_text, r) in to_show:
            name = Path(r["path"]).relative_to(repo_root)
            action = r.get("action", "")
            print(f"\n### [{label}] {name}  (action: {action}, ~{size} lines changed)\n")
            print(diff_text or "  (no textual diff — content reordered)")
            print()

        # List all other modified files without showing diffs
        others = [e for e in enriched if e not in [x[1] for x in to_show]]
        if others:
            print(f"  All {len(modified)} modified files (by change size):")
            for size, _, r in enriched:
                name = Path(r["path"]).relative_to(repo_root)
                print(f"    {size:3d} lines  {name}")
        print()


