def _strip_fences(text: str) -> str:
    """Remove leading/trailing markdown code fences that LLMs sometimes add."""
    text = text.strip()
    if text.startswith("```yaml"):
        text = text[7:]
    elif text.startswith("```"):
        text = text[3:]
    if text.endswith("```"):
        text = text[:-3]
    return text.strip()


def _extract_flag(raw: str) -> tuple[str | None, str]:
    """
    If the LLM prepended 'FLAGGED: <reason>' before the yaml, extract it.
    Returns (reason_or_None, clean_yaml_text).
    """
    first_line, sep, rest = raw.partition("\n")
    if first_line.startswith("FLAGGED:"):
        return first_line[len("FLAGGED:"):].strip(), rest.strip()
    return None, raw


# Which token-limit kwarg the installed openai client accepts. Newer libraries/
# models use `max_completion_tokens`; older ones only know `max_tokens`. Detected
# once on the first call and reused.
_MAX_TOKENS_PARAM: str | None = None


def _chat(client: OpenAI, model: str, system: str, user: str, temperature: float = 0.3,
          max_tokens: int = 4096) -> str:
    global _MAX_TOKENS_PARAM
    messages = [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]

    def _create(param: str):
        return _call_with_retry(
            client.chat.completions.create,
            model=model,
            messages=messages,
            temperature=temperature,
            **{param: max_tokens},
        )

    if _MAX_TOKENS_PARAM is None:
        try:
            response = _create("max_completion_tokens")
            _MAX_TOKENS_PARAM = "max_completion_tokens"
        except TypeError as exc:
            if "max_completion_tokens" not in str(exc):
                raise
            response = _create("max_tokens")
            _MAX_TOKENS_PARAM = "max_tokens"
    else:
        response = _create(_MAX_TOKENS_PARAM)

    return response.choices[0].message.content.strip()


