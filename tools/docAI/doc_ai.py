_LEFTOVER_FLAG_RE = re.compile(r'[ \t]*toctreehere[ \t]*\r?\n?$', re.IGNORECASE)


def _strip_leftover_flags(text: str) -> str:
    """Remove standalone 'toctreeHere' placeholder lines (leftovers from an old
    doc workflow that now render as literal text), dropping one adjacent blank
    line so no double gap is left. Preserves the file's newline style."""
    lines = text.splitlines(keepends=True)
    out: list[str] = []
    i = 0
    while i < len(lines):
        if _LEFTOVER_FLAG_RE.fullmatch(lines[i]):
            i += 1
            if i < len(lines) and lines[i].strip() == "":
                i += 1  # also consume one trailing blank line
            continue
        out.append(lines[i])
        i += 1
    return "".join(out)


def _is_skeleton_page(text: str) -> bool:
    """True if a guide page is essentially just a title + toctree (+ anchors/
    spacers) with no real prose — a candidate for an AI-generated introduction.
    """
    in_directive = False
    directive_indent = 0
    prose_words = 0
    for raw in text.splitlines():
        ln = raw.rstrip("\r\n")
        s = ln.strip()
        if not s:
            in_directive = False
            continue
        if re.match(r'^\.\. _[\w./-]+:\s*$', s):          # RST anchor
            continue
        if re.match(r'^\([\w.-]+\)=\s*$', s):              # MyST target
            continue
        if re.match(r'^\.\. [\w-]+::', s) or re.match(r'^(?:`{3,}|:{3,})\{[\w-]+\}', s):
            in_directive = True
            directive_indent = len(ln) - len(ln.lstrip())
            continue
        indent = len(ln) - len(ln.lstrip())
        if in_directive and indent > directive_indent:     # directive body/options
            continue
        if re.match(r'^:[\w-]+:', s):                      # stray directive option
            continue
        if re.fullmatch(r'[=\-~^"#*+.`\']{3,}', s):        # heading underline/overline
            continue
        if re.fullmatch(r'(?:`{3,}|:{3,}|<[^>]+>)', s):    # fence close / raw html
            continue
        in_directive = False
        prose_words += len(s.lstrip('# ').split())         # MD heading hashes stripped
    # Only the title's own words should remain on a skeleton page.
    return prose_words <= 8


def find_skeleton_index_files(repo_root: Path) -> list[Path]:
    """Return usersguide index pages that are just a title + toctree (no prose)."""
    guide_dir = repo_root / "documentation" / "sphinx" / "usersguide"
    if not guide_dir.exists():
        return []
    out: list[Path] = []
    for p in sorted(guide_dir.rglob("*")):
        if p.suffix not in (".rst", ".md") or p.stem != "index":
            continue
        try:
            text = p.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            continue
        if (".. toctree::" in text or "{toctree}" in text) and _is_skeleton_page(text):
            out.append(p)
    return out


def _rst_structural_elements(text: str) -> set[str]:
    """
    Extract RST anchors, directive names, and toctree entry paths.
    Used to validate that the LLM hasn't dropped structural content.
    """
    import re
    # Cross-reference labels:  .. _some-label:
    anchors = set(re.findall(r"\.\. _[\w./-]+:", text))
    # Directive names (no trailing space required — catches '.. toctree::' alone on a line)
    directives = set(re.findall(r"\.\. (\w[\w-]*)::[ \t\n]", text))
    # Toctree entry paths (lines indented inside a toctree block)
    toctree_entries = set(re.findall(r"^\s+(?:[^<\n]+<)?((?:\.\./)+[\w./]+)>?\s*$", text, re.MULTILINE))
    return anchors | directives | toctree_entries


def _md_structural_elements(text: str) -> set[str]:
    """
    Extract MyST/Markdown heading anchors, explicit targets, and directive names.
    Used to validate that the LLM hasn't dropped structural content.
    """
    # Heading attribute anchors:  {#some-anchor}
    anchors = set(re.findall(r"\{#[\w.-]+\}", text))
    # Explicit MyST targets:  (some-target)=
    targets = set(re.findall(r"^\([\w.-]+\)=\s*$", text, re.MULTILINE))
    # Fenced/colon directives:  ```{name}  or  :::{name}
    directives = set(re.findall(r"^(?:`{3,}|:{3,})\{(\w[\w-]*)\}", text, re.MULTILINE))
    return anchors | targets | directives


def polish_guide_file(
    client: OpenAI,
    rst_path: Path,
    model: str,
    cache: dict,
    dry_run: bool,
    verbose: bool,
    output_dir: Path | None = None,
) -> dict:
    """Improve English and formatting of a single usersguide file (RST or Markdown)."""
    result: dict = {"path": str(rst_path), "action": "none"}

    is_md = rst_path.suffix == ".md"
    system_prompt = _SYSTEM_GUIDE_POLISHER_MD if is_md else _SYSTEM_GUIDE_POLISHER
    fmt_label = "Markdown (MyST)" if is_md else "RST"
    elements_of = _md_structural_elements if is_md else _rst_structural_elements

    original = rst_path.read_text(encoding="utf-8")

    # Never send empty/near-empty files to the LLM: it has nothing to polish
    # and tends to reply conversationally, which would be saved as content.
    if len(original.strip()) < 40:
        result["from_cache"] = False
        return result

    content_hash = hashlib.md5(original.encode()).hexdigest()[:8]
    cache_key = f"guide|{rst_path}|{model}|{content_hash}"

    result["from_cache"] = cache_key in cache

    if cache_key in cache:
        improved = cache[cache_key]
    else:
        user_prompt = f"Improve the following {fmt_label} file:\n\n{original}"
        improved = _call_with_retry(
            _chat, client, model, system_prompt, user_prompt, 0.2,
            max(4096, len(original) // 3),
        )
        # Strip accidental fences
        if improved.startswith("```"):
            improved = improved.split("\n", 1)[1] if "\n" in improved else improved
            if improved.endswith("```"):
                improved = improved[:-3].rstrip()

    # Remove leftover 'toctreeHere' placeholder lines regardless of what the LLM
    # did, so a file whose only needed change is that removal still gets written.
    improved = _strip_leftover_flags(improved)

    # Validate structural elements are preserved
    orig_elements = elements_of(original)
    new_elements = elements_of(improved)
    missing = orig_elements - new_elements
    if missing:
        result["error"] = f"LLM dropped structural elements: {', '.join(sorted(missing))}"
        if verbose:
            print(f"    SKIP — missing elements: {', '.join(sorted(missing))}")
        return result

    if improved == original:
        result["action"] = "none"
        cache[cache_key] = improved
        return result

    result["action"] = "polished"
    result["new_content"] = improved
    result["original"] = original
    cache[cache_key] = improved

    if not dry_run:
        _resolve_output_path(rst_path, output_dir).write_text(improved, encoding="utf-8")

    return result


def _toctree_entries(text: str) -> list[str]:
    """Return the document paths listed inside a page's toctree block(s)
    (both RST ``.. toctree::`` and MyST ```` ```{toctree} ````)."""
    entries: list[str] = []
    in_toctree = False
    for raw in text.splitlines():
        s = raw.strip()
        if re.match(r'^\.\. toctree::', s) or re.match(r'^(?:`{3,}|:{3,})\{toctree\}', s):
            in_toctree = True
            continue
        if not in_toctree:
            continue
        if not s:
            continue
        if s.startswith(":"):                       # directive option (:maxdepth: ...)
            continue
        if re.match(r'^\.\. ', s) or re.match(r'^(?:`{3,}|:{3,})', s):
            in_toctree = False                       # next directive / fence close
            continue
        m = re.match(r'^(?:[^<]*<)?([^>]+)>?$', s)    # 'Title <path>' or bare 'path'
        if m:
            entries.append(m.group(1).strip())
    return entries


def _page_title(path: Path) -> str:
    """Best-effort first heading of an RST/MD page (for child-section context)."""
    try:
        lines = path.read_text(encoding="utf-8", errors="ignore").splitlines()
    except OSError:
        return path.stem
    for i, raw in enumerate(lines):
        s = raw.strip()
        if not s or re.match(r'^\.\. ', s) or re.match(r'^\([\w.-]+\)=', s):
            continue
        if s.startswith("#"):                                    # Markdown heading
            return s.lstrip("# ").strip()
        if i + 1 < len(lines) and re.fullmatch(r'[=\-~^"#*+.`\']{3,}', lines[i + 1].strip()):
            return s                                             # RST title + underline
    return path.stem


def generate_index_intro(
    client: OpenAI,
    rst_path: Path,
    model: str,
    cache: dict,
    dry_run: bool,
    output_dir: Path | None = None,
) -> dict:
    """Generate a short introduction for a skeleton index page (title + toctree,
    no prose) and insert it between the title and the toctree. Writes to the AI
    content tree; the original (standard build) keeps its bare index."""
    result: dict = {"path": str(rst_path), "action": "none"}
    original = rst_path.read_text(encoding="utf-8")
    is_md = rst_path.suffix == ".md"

    title = _page_title(rst_path)
    child_titles = []
    for entry in _toctree_entries(original):
        cand = (rst_path.parent / entry)
        for suffix in (".rst", ".md"):
            f = cand.with_suffix(suffix)
            if f.exists():
                child_titles.append(_page_title(f))
                break
        else:
            child_titles.append(entry.rsplit("/", 1)[-1])

    content_hash = hashlib.md5(original.encode()).hexdigest()[:8]
    cache_key = f"guide-intro|{rst_path}|{model}|{content_hash}"
    result["from_cache"] = cache_key in cache

    if cache_key in cache:
        intro = cache[cache_key]
    else:
        children = "\n".join(f"- {t}" for t in child_titles) or "(none listed)"
        fmt = "Markdown (MyST)" if is_md else "reStructuredText"
        user_prompt = (
            f"Write a short introduction (2-4 sentences, one paragraph) for the "
            f"foamForNuclear user-guide section titled \"{title}\". The section "
            f"groups these subsections:\n{children}\n\n"
            f"Explain in plain {fmt} prose what this section covers and how the "
            f"subsections fit together, for graduate students in nuclear "
            f"engineering. Output ONLY the paragraph text: no heading, no title, "
            f"no toctree, no lists, no markup fences."
        )
        intro = _call_with_retry(
            _chat, client, model, _SYSTEM_GUIDE_INTRO, user_prompt, 0.3, 600
        ).strip()
        if intro.startswith("```"):
            intro = intro.split("\n", 1)[-1].rsplit("```", 1)[0].strip()
        cache[cache_key] = intro

    if not intro:
        return result

    newline = "\r\n" if "\r\n" in original else "\n"
    lines = original.split(newline)
    # Insert the intro just before the first toctree directive.
    insert_at = next(
        (i for i, ln in enumerate(lines)
         if re.match(r'^\s*\.\. toctree::', ln)
         or re.match(r'^\s*(?:`{3,}|:{3,})\{toctree\}', ln)),
        None,
    )
    if insert_at is None:
        return result
    block = intro.split("\n")
    new_lines = lines[:insert_at] + block + [""] + lines[insert_at:]
    new_content = newline.join(new_lines)

    if new_content == original:
        return result
    result["action"] = "intro-added"
    result["new_content"] = new_content
    result["original"] = original
    if not dry_run:
        _resolve_output_path(rst_path, output_dir).write_text(new_content, encoding="utf-8")
    return result


