def generate_yaml(
    client: OpenAI,
    yaml_path: Path,
    source_info: dict,
    existing_yaml: str,
    few_shot: str,
    model: str,
    theory_model: str,
    add_theory: bool,
    cache: dict,
    tutorial_snippets: list[str] | None = None,
) -> str:
    """
    Generate a complete yaml for an incomplete file.
    Uses source code + few-shot examples as context.
    If add_theory, uses theory_model for the formulation section.
    tutorial_snippets: real usage examples found in tutorials/ for the usage field.
    """
    class_name = source_info["class_name"]
    src_ctx = build_source_context(source_info)

    # Key includes a hash of stub + source so changed code invalidates the cache
    ctx_hash = hashlib.md5((existing_yaml + src_ctx).encode()).hexdigest()[:8]
    cache_key = f"generate_v2|{yaml_path}|{model}|{theory_model}|{add_theory}|{ctx_hash}"
    if cache_key in cache:
        return cache[cache_key]

    tutorial_ctx = ""
    if tutorial_snippets:
        tutorial_ctx = "\n\n## Tutorial usage examples (use these verbatim for the `usage` field):\n"
        tutorial_ctx += "\n\n".join(tutorial_snippets)
    else:
        try:
            _stub_usage = (yaml.safe_load(existing_yaml) or {}).get("usage")
        except Exception:
            _stub_usage = None
        if _stub_usage:
            tutorial_ctx = (
                "\n\n## Usage: the stub already contains usage examples. "
                "Copy the `usage` field verbatim into the output — do not modify or remove it."
            )
        else:
            tutorial_ctx = "\n\n## Tutorial usage: none found — set `usage: []` in the yaml."

    # --- Step 1: code analysis → structured yaml (without formulation) ---
    user_prompt_code = f"""Generate a complete yaml documentation file for the C++ class `{class_name}`.

## Source code:{src_ctx if src_ctx else "\n(No adjacent .H/.C files found — infer from class name and yaml stub.)"}

## Current stub (improve this, remove the warning admonition):
```yaml
{existing_yaml}
```

## Style examples (match this format exactly):
{few_shot[:3000]}
{tutorial_ctx}

Generate the yaml now. Return only the yaml content."""

    system = _SYSTEM_CODE_ANALYST
    if add_theory:
        system = _SYSTEM_CODE_ANALYST + "\n\n" + _SYSTEM_THEORY_WRITER

    raw_code = _chat(client, model, system, user_prompt_code, temperature=0.25)
    flag, raw_code = _extract_flag(raw_code)
    if flag:
        cache[f"source_flag|{yaml_path}"] = flag
    result = _strip_fences(raw_code)

    # --- Step 2: if separate theory model, regenerate only the formulation ---
    if add_theory and theory_model != model and src_ctx:
        # Parse result to check if formulation already good; otherwise enhance
        user_prompt_theory = f"""The following yaml documentation for `{class_name}` needs a high-quality
`formulation` section explaining the physical model mathematically.

## Source code for context:{src_ctx}

## Current yaml (add or improve the formulation field):
```yaml
{result}
```

Return the full corrected yaml with an improved `formulation` section.
Return only the yaml content."""

        result = _strip_fences(_chat(
            client, theory_model, _SYSTEM_THEORY_WRITER, user_prompt_theory, temperature=0.4
        ))

    cache[cache_key] = result
    return result


def _normalize_yaml_value(v):
    """Normalize parsed yaml for semantic comparison: drop None-valued dict
    entries (key absent vs key empty are equivalent) and trailing whitespace."""
    if isinstance(v, dict):
        return {k: _normalize_yaml_value(x) for k, x in v.items() if x is not None}
    if isinstance(v, list):
        return [_normalize_yaml_value(x) for x in v]
    if isinstance(v, str):
        return v.rstrip()
    return v


def _changed_sections(old_yaml: str, new_yaml: str) -> list[str]:
    """Return top-level yaml keys whose values SEMANTICALLY differ between old
    and new (re-serialization noise like dropped empty defaults is ignored)."""
    try:
        old = yaml.safe_load(old_yaml) or {}
        new = yaml.safe_load(new_yaml) or {}
        return [
            k for k in new
            if k not in ("ai_provenance",)
            and _normalize_yaml_value(old.get(k)) != _normalize_yaml_value(new.get(k))
        ]
    except Exception:
        return []


def _restore_dropped_options(orig: dict, new: dict) -> bool:
    """
    Restore options/externalOptions/optionsLocations that the LLM dropped from
    the original, matched by (key, location, path). The model only ever sees a
    truncated source excerpt, so "I did not find this option in the code" is
    not evidence of absence. Mutates ``new`` in place; returns True if anything
    was restored.
    """
    def _opt_id(o):
        return (o.get("key"), o.get("location"), o.get("path"))

    changed = False
    for field in ("options", "externalOptions"):
        orig_opts = [o for o in (orig.get(field) or []) if isinstance(o, dict)]
        new_opts = [o for o in (new.get(field) or []) if isinstance(o, dict)]
        new_ids = {_opt_id(o) for o in new_opts}
        dropped = [o for o in orig_opts if _opt_id(o) not in new_ids]
        if dropped:
            new[field] = new_opts + dropped
            changed = True

    if orig.get("optionsLocations") and not new.get("optionsLocations"):
        new["optionsLocations"] = orig["optionsLocations"]
        changed = True

    if orig.get("dictionary") and not new.get("dictionary"):
        new["dictionary"] = orig["dictionary"]
        changed = True

    return changed


def _preserve_human_content(existing_yaml: str, corrected: str) -> str:
    """
    Safety net after a consistency check: never let the LLM silently drop
    human-written content. Restores options/externalOptions removed from the
    original (matched by key+location), the original usage examples, and
    optionsLocations. The LLM only ever sees a truncated source excerpt, so
    "I did not find this option in the code" is not evidence of absence.
    """
    try:
        orig = yaml.safe_load(existing_yaml) or {}
        new = yaml.safe_load(corrected) or {}
        if not isinstance(orig, dict) or not isinstance(new, dict):
            return corrected
    except Exception:
        return corrected

    changed = _restore_dropped_options(orig, new)

    # usage is human-written and the prompt forbids touching it — enforce that
    if orig.get("usage") and \
            _normalize_yaml_value(new.get("usage")) != _normalize_yaml_value(orig.get("usage")):
        new["usage"] = orig["usage"]
        changed = True

    if changed:
        return _yaml_dump(new)
    return corrected


def _set_ai_provenance(yaml_str: str, model: str, **fields) -> str:
    """
    Insert or update the ai_provenance metadata block in a yaml string.
    Extra keyword arguments (generated, modified_sections, formulation_added, etc.)
    are merged into the block.
    """
    try:
        data = yaml.safe_load(yaml_str) or {}
    except Exception as exc:
        raise ValueError(f"LLM returned invalid yaml: {exc}\n---\n{yaml_str[:300]}") from exc
    prov = data.get("ai_provenance") or {}
    prov["model"] = model
    prov["date"] = date.today().isoformat()
    prov.update(fields)
    data["ai_provenance"] = prov
    return _yaml_dump(data)


def _extract_rst_toctrees(text: str) -> list[str]:
    """Return all ``.. toctree::`` blocks found in RST text (as raw strings)."""
    blocks = []
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        if re.match(r'^\s*\.\. toctree::', lines[i]):
            block_lines = [lines[i]]
            i += 1
            # Collect indented continuation lines (options and entries) plus
            # blank lines that appear before the next indented line.
            while i < len(lines):
                line = lines[i]
                if line.strip() == "":
                    block_lines.append(line)
                    i += 1
                elif re.match(r'^\s+', line):
                    block_lines.append(line)
                    i += 1
                else:
                    break
            # Strip trailing blank lines from the block
            while block_lines and block_lines[-1].strip() == "":
                block_lines.pop()
            blocks.append("\n".join(block_lines))
        else:
            i += 1
    return blocks


def _preserve_description_toctrees(orig_desc: str, new_desc: str) -> str:
    """
    If the original description contained ``.. toctree::`` blocks that are
    absent from the new description, append them at the end.
    """
    orig_blocks = _extract_rst_toctrees(orig_desc)
    if not orig_blocks:
        return new_desc
    new_blocks = _extract_rst_toctrees(new_desc)
    missing = [b for b in orig_blocks if b not in new_blocks]
    if not missing:
        return new_desc
    return new_desc.rstrip() + "\n\n" + "\n\n".join(missing)


def _merge_yaml_update(existing_yaml: str, partial_yaml: str) -> str:
    """
    Merge LLM-returned yaml into the existing yaml.
    Top-level keys present in partial_yaml overwrite those in existing_yaml.
    Keys absent from partial_yaml are preserved unchanged.
    Falls back to partial_yaml as-is if parsing fails.
    """
    try:
        base = yaml.safe_load(existing_yaml) or {}
        patch = yaml.safe_load(partial_yaml) or {}
        if isinstance(base, dict) and isinstance(patch, dict):
            merged = {**base, **patch}
            return _yaml_dump(merged)
    except Exception:
        pass
    return partial_yaml


