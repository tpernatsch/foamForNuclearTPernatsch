def find_all_yaml_files(repo_root: Path) -> list[Path]:
    """Return all yaml sidecar files in src/ and applications/, plus expected paths for
    classes that have both .H and .C but no yaml yet."""
    found: set[Path] = set()
    for search_dir in [repo_root / "src", repo_root / "applications"]:
        if not search_dir.exists():
            continue
        for p in search_dir.rglob("*.yaml"):
            if any(part in EXCLUDE_YAML_PARTS for part in p.parts):
                continue
            found.add(p)
        # Add expected yaml paths for concrete classes (.H + .C + class declaration)
        for h_path in search_dir.rglob("*.H"):
            if any(part in EXCLUDE_YAML_PARTS for part in h_path.parts):
                continue
            if not h_path.with_suffix(".C").exists():
                continue
            yaml_path = h_path.with_suffix(".yaml")
            if yaml_path in found:
                continue
            try:
                h_text = h_path.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                continue
            if not re.search(r'^class\s+', h_text, re.MULTILINE):
                continue
            found.add(yaml_path)
    return sorted(found)


_PROGRESS_LINK_RE = re.compile(r'\[([^\]]+\.yaml)\]\(https?://[^)]+\)')


def load_progress_paths(repo_root: Path) -> frozenset[Path]:
    """Parse yaml_progress.md and return absolute paths of incomplete yaml files."""
    md_path = repo_root / "documentation" / "sphinx" / "cppapi" / "yaml_progress.md"
    if not md_path.exists():
        return frozenset()
    text = md_path.read_text(encoding="utf-8", errors="ignore")
    return frozenset(repo_root / m.group(1) for m in _PROGRESS_LINK_RE.finditer(text))


def is_incomplete(yaml_path: Path, progress_paths: frozenset = frozenset()) -> bool:
    """True if the yaml file needs generation or improvement.

    Triggers on any of:
      - file does not exist
      - file is blank / unparseable
      - file contains the INCOMPLETE_MARKER admonition
      - file is listed in yaml_progress.md AND has no ai_provenance yet
      - file has no usage examples AND has never been AI-processed
    """
    if not yaml_path.exists():
        return True
    try:
        content = yaml_path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return True
    if not content.strip():
        return True
    if INCOMPLETE_MARKER in content:
        return True
    try:
        data = yaml.safe_load(content) or {}
    except Exception:
        data = {}
    has_provenance = bool(data.get("ai_provenance"))
    # Progress file lists files that still need work; skip if AI already processed it
    if yaml_path in progress_paths and not has_provenance:
        return True
    # No usage examples and never AI-processed → still needs generation
    if not data.get("usage") and not has_provenance:
        return True
    return False


