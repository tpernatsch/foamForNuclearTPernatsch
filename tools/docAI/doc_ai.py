# Dictionary-access patterns: where OpenFOAM code reads run-time options
# (dict.lookup(), get<T>(), getOrDefault<>(), readScalar(), subDict(), found(), ...).
_DICT_READ_RE = re.compile(
    r'\b(?:lookup\w*|get(?:OrDefault)?|read(?:Scalar|Label|Bool|Word|Entry|IfPresent)\w*'
    r'|sub(?:Dict|OrEmptyDict)|found|isDict)\s*[<(]'
)

# Dictionary-definition patterns: where the input FILE a class reads from is
# named — e.g. IOobject("neutronicsProperties", ...), IOdictionary construction.
# These sites usually live in the constructor, away from the lookup calls, so
# the `dictionary` field would be missed if only read sites were surfaced.
# The (?!::) guard skips scope-resolution uses like IOobject::READ_IF_PRESENT,
# which otherwise match on nearly every constructor line and chain the windows
# into one giant block.
_DICT_DEFINE_RE = re.compile(r'\b(?:IO(?:object|dictionary)|regIOobject)\b(?!::)')


def _read_aware_excerpt(text: str, budget: int, context_lines: int = 6,
                        head_lines: int = 30) -> str:
    """
    Return an excerpt of ``text`` no longer than ``budget`` characters that
    preferentially includes the regions where the code reads from input
    dictionaries (option discovery) and where it names the dictionary FILE it
    reads from (the `dictionary` field), so both work even when those sites sit
    deep in a long .C file. A plain head slice silently misses constructors that
    appear after a lot of preamble (license, includes, static members). Elided
    spans are marked with a comment. Text already within budget — or with no
    detectable dictionary sites — is returned as a normal head slice.
    """
    if len(text) <= budget:
        return text

    lines = text.splitlines()
    n = len(lines)
    read_lines = [i for i, ln in enumerate(lines) if _DICT_READ_RE.search(ln)]
    define_lines = [i for i, ln in enumerate(lines) if _DICT_DEFINE_RE.search(ln)]
    if not read_lines and not define_lines:
        return text[:budget]

    cost = [len(ln) + 1 for ln in lines]  # +1 for the newline

    def _merge(intervals):
        out: list[list[int]] = []
        for lo, hi in sorted(intervals):
            if out and lo <= out[-1][1]:
                out[-1][1] = max(out[-1][1], hi)
            else:
                out.append([lo, hi])
        return [(lo, hi) for lo, hi in out]

    def _windows(line_idxs, ctx):
        return _merge(
            (max(0, i - ctx), min(n, i + ctx + 1)) for i in line_idxs
        )

    # Reads get a generous window (need surrounding logic to infer type/default);
    # define sites get a tight one so the file-name string is not buried in a big
    # merged block of consecutive field-registration IOobjects.
    read_wins = _windows(read_lines, context_lines)
    define_wins = _windows(define_lines, 4)
    head_win = (0, min(head_lines, n))

    selected: list[tuple[int, int]] = []
    used = 0

    def _take(windows, cap):
        """Add windows in file order while staying under ``cap`` total chars. A
        window larger than the remaining room is truncated to its leading lines
        rather than dropped, so a single dense read-region still fills the budget
        instead of leaving the excerpt nearly empty."""
        nonlocal used
        for lo, hi in windows:
            if (lo, hi) in selected:
                continue
            if used + sum(cost[lo:hi]) <= cap:
                selected.append((lo, hi))
                used += sum(cost[lo:hi])
                continue
            end, acc = lo, 0
            while end < hi and used + acc + cost[end] <= cap:
                acc += cost[end]
                end += 1
            if end > lo:
                selected.append((lo, end))
                used += acc

    # Reserve a small slice for the earliest dictionary-name site(s) so the
    # `dictionary` field is discoverable even on read-heavy files, then spend the
    # bulk on option reads (the primary signal), then backfill remaining
    # define sites and the head for class context.
    _take(define_wins, min(used + max(budget // 5, 600), budget))
    _take(read_wins, budget)
    _take(define_wins + [head_win], budget)

    if not selected:
        return text[:budget]

    parts: list[str] = []
    prev_hi = 0
    for lo, hi in _merge(selected):
        if lo > prev_hi:
            parts.append(f"// ... [{lo - prev_hi} line(s) omitted] ...")
        parts.extend(lines[lo:hi])
        prev_hi = hi
    if prev_hi < n:
        parts.append(f"// ... [{n - prev_hi} line(s) omitted] ...")
    return "\n".join(parts)


# Optional global override for the per-file source-context budget (chars),
# set from the CLI (--source-budget / --full-source). It can only RAISE a
# call site's budget, never lower it, so the read-aware excerpting still
# applies the same priorities — there is just more room. A very large value
# effectively sends whole files. None = use each call site's default.
SOURCE_BUDGET_OVERRIDE: int | None = None


def build_source_context(source_info: dict, max_header: int = 8000, max_impl: int = 4000) -> str:
    """Format source files as a context string for LLM prompts."""
    if SOURCE_BUDGET_OVERRIDE is not None:
        max_header = max(max_header, SOURCE_BUDGET_OVERRIDE)
        max_impl = max(max_impl, SOURCE_BUDGET_OVERRIDE)
    name = source_info["class_name"]
    ctx = ""
    if "header" in source_info:
        hdr = _read_aware_excerpt(source_info["header"], max_header)
        ctx += f"\n### {name}.H\n```cpp\n{hdr}\n```"
    if "implementation" in source_info:
        impl = _read_aware_excerpt(source_info["implementation"], max_impl)
        ctx += f"\n### {name}.C\n```cpp\n{impl}\n```"
    return ctx


