def main() -> None:
    args = parse_args()
    verbose = not args.quiet
    theory_model = args.theory_model or args.model
    add_theory = not args.no_theory
    output_dir = Path(args.output_dir).resolve() if args.output_dir else None

    # A larger source-context budget invalidates the generate/check caches
    # (their keys hash the source excerpt), so changed files are re-processed.
    global SOURCE_BUDGET_OVERRIDE
    if args.full_source:
        SOURCE_BUDGET_OVERRIDE = 10_000_000
    elif args.source_budget is not None:
        SOURCE_BUDGET_OVERRIDE = args.source_budget

    if verbose:
        print("foamForNuclear AI Documentation Generator")
        print(f"  Repo root       : {REPO_ROOT}")
        print(f"  Mode            : {args.mode}")
        print(f"  Model           : {args.model}")
        print(f"  Theory model    : {theory_model}")
        print(f"  Add theory      : {add_theory}")
        print(f"  Dry run         : {args.dry_run}")
        print(f"  Output dir      : {output_dir or '(in-place)'}")
        if SOURCE_BUDGET_OVERRIDE is not None:
            budget_label = "whole files" if args.full_source else f"{SOURCE_BUDGET_OVERRIDE} chars"
            print(f"  Source budget   : {budget_label}")
        print()

    client = get_client()

    # --- Cache ----------------------------------------------------------------
    cache_path = _SCRIPT_DIR / ".llm_cache.json"
    cache: dict = {}
    if not args.no_cache and cache_path.exists():
        with open(cache_path, encoding="utf-8") as fh:
            cache = json.load(fh)
        if verbose:
            print(f"Loaded {len(cache)} cached LLM responses from {cache_path.name}")

    def save_cache() -> None:
        if not args.no_cache:
            with open(cache_path, "w", encoding="utf-8") as fh:
                json.dump(cache, fh, indent=2)

    # --- Build shared context -------------------------------------------------
    few_shot = load_few_shot_examples(REPO_ROOT)
    sphinx_index = load_sphinx_index(REPO_ROOT)
    if verbose and sphinx_index:
        print(f"Loaded sphinx index ({len(sphinx_index)} chars) as project context.")
        print()

    progress_paths = load_progress_paths(REPO_ROOT)

    all_results: list[dict] = []

    # =========================================================================
    # Documentation generation / consistency checking
    # =========================================================================
    if args.mode in ("generate", "check", "all"):

        # Determine which files to process
        if args.files:
            yaml_files: list[Path] = []
            for f in args.files:
                p = Path(f)
                if not p.is_absolute():
                    p = REPO_ROOT / p
                yaml_files.append(p)  # include even if missing; is_incomplete handles it
        else:
            yaml_files = find_all_yaml_files(REPO_ROOT)

        # Filter by mode
        if args.mode == "generate" and not args.force:
            to_process = [f for f in yaml_files if is_incomplete(f, progress_paths)]
        elif args.mode == "check":
            to_process = [f for f in yaml_files if not is_incomplete(f, progress_paths)]
        else:  # all
            to_process = yaml_files

        if verbose:
            mode_label = args.mode if args.mode != "all" else "generate+check"
            print(f"=== Documentation ({mode_label}) ===")
            print(f"Total yaml files   : {len(yaml_files)}")
            incomplete_count = sum(1 for f in yaml_files if is_incomplete(f, progress_paths))
            print(f"Incomplete (stub)  : {incomplete_count}")
            print(f"Files to process   : {len(to_process)}")
            if args.dry_run:
                print("  [DRY RUN — no files will be written]")
            print()

        generated = updated = formulation_added = formulation_extended = errors = 0

        for i, yaml_path in enumerate(to_process, 1):
            rel = yaml_path.relative_to(REPO_ROOT)
            if verbose:
                # Cache status is checked inside process_yaml_file; print after
                pass

            file_result = process_yaml_file(
                client=client,
                yaml_path=yaml_path,
                mode=args.mode,
                model=args.model,
                theory_model=theory_model,
                add_theory=add_theory,
                dry_run=args.dry_run,
                force=args.force,
                few_shot=few_shot,
                cache=cache,
                verbose=verbose,
                progress_paths=progress_paths,
                output_dir=output_dir,
            )
            all_results.append(file_result)

            action = file_result.get("action", "none")
            cached_tag = " [cached]" if file_result.get("from_cache") else ""
            if verbose:
                print(f"[{i}/{len(to_process)}] {rel}{cached_tag}")

            if "generated" in action:
                generated += 1
                if verbose:
                    print(f"    -> generated")
            if "consistency-updated" in action:
                updated += 1
                if verbose:
                    print(f"    -> consistency fixed")
            if "+formulation-extended" in action:
                formulation_extended += 1
                if verbose:
                    print(f"    -> formulation extended")
            elif "+formulation" in action:
                formulation_added += 1
                if verbose:
                    print(f"    -> formulation added")
            if file_result.get("error"):
                errors += 1

            # Save cache periodically
            if i % 10 == 0:
                save_cache()

            # Skip rate-limit delay when result came from cache
            if not file_result.get("from_cache"):
                time.sleep(API_RATE_DELAY)

        # Collect source-content flags raised during generate/check
        source_flags = [
            (r["path"], r["source_flag"])
            for r in all_results
            if r.get("source_flag")
        ]

        print()
        print("Summary:")
        print(f"  Generated           : {generated}")
        print(f"  Consistency fixed   : {updated}")
        print(f"  Formulation added   : {formulation_added}")
        print(f"  Formulation extended: {formulation_extended}")
        print(f"  Source flags        : {len(source_flags)}")
        print(f"  Errors              : {errors}")

        if source_flags:
            print("\nFlagged source files (see tools/docAI/content_flags.md):")
            for path, reason in source_flags:
                rel = Path(path).relative_to(REPO_ROOT)
                print(f"  {rel}  —  {reason}")

        # Write / update content_flags.md
        flags_path = REPO_ROOT / "tools" / "docAI" / "content_flags.md"
        if source_flags:
            lines = ["# Source content flags\n",
                     "Files flagged by the AI doc generator for potentially inappropriate"
                     " language in source comments.\n",
                     "Fix the issue, then remove the entry.\n\n"]
            for path, reason in source_flags:
                rel = Path(path).relative_to(REPO_ROOT)
                # Link to the adjacent source file, not the yaml
                src_candidates = list(Path(path).parent.glob(
                    Path(path).stem + ".H"
                )) + list(Path(path).parent.glob(Path(path).stem + ".C"))
                src_link = str(Path(src_candidates[0]).relative_to(REPO_ROOT)) \
                    if src_candidates else str(rel)
                lines.append(f"- [{src_link}]({src_link})  —  {reason}\n")
            flags_path.write_text("".join(lines), encoding="utf-8")
        elif flags_path.exists():
            # All flags resolved — clear the file
            flags_path.write_text(
                "# Source content flags\n\nNo issues found.\n", encoding="utf-8"
            )

        if args.dry_run:
            doc_results = [r for r in all_results if "path" in r]
            print_dry_run_report(doc_results, REPO_ROOT)

    # =========================================================================
    # User guide polishing
    # =========================================================================
    if args.mode in ("guide", "all"):
        rst_files = find_all_guide_files(REPO_ROOT)

        if verbose:
            print(f"=== User guide polishing ===")
            print(f"Guide files to process (rst+md): {len(rst_files)}")
            if args.dry_run:
                print("  [DRY RUN — no files will be written]")
            print()

        guide_polished = guide_skipped = guide_errors = 0

        for i, rst_path in enumerate(rst_files, 1):
            rel = rst_path.relative_to(REPO_ROOT)
            result = polish_guide_file(
                client=client,
                rst_path=rst_path,
                model=args.model,
                cache=cache,
                dry_run=args.dry_run,
                verbose=verbose,
                output_dir=output_dir,
            )
            all_results.append(result)

            cached_tag = " [cached]" if result.get("from_cache") else ""
            if verbose:
                print(f"[{i}/{len(rst_files)}] {rel}{cached_tag}")

            if result.get("error"):
                guide_errors += 1
                if verbose:
                    print(f"    ERROR: {result['error']}")
            elif result.get("action") == "polished":
                guide_polished += 1
                if verbose:
                    print(f"    -> polished")
            else:
                guide_skipped += 1

            if not result.get("from_cache"):
                time.sleep(API_RATE_DELAY)

            if i % 10 == 0:
                save_cache()

        # --- Introductions for skeleton index pages (title + toctree only) ----
        skeleton_indexes = find_skeleton_index_files(REPO_ROOT)
        intros_added = 0
        if verbose and skeleton_indexes:
            print()
            print(f"Skeleton index pages needing an intro: {len(skeleton_indexes)}")
        for j, idx_path in enumerate(skeleton_indexes, 1):
            rel = idx_path.relative_to(REPO_ROOT)
            res = generate_index_intro(
                client=client,
                rst_path=idx_path,
                model=args.model,
                cache=cache,
                dry_run=args.dry_run,
                output_dir=output_dir,
            )
            all_results.append(res)
            cached_tag = " [cached]" if res.get("from_cache") else ""
            if verbose:
                print(f"[intro {j}/{len(skeleton_indexes)}] {rel}{cached_tag}")
            if res.get("action") == "intro-added":
                intros_added += 1
                if verbose:
                    print("    -> intro added")
            if not res.get("from_cache"):
                time.sleep(API_RATE_DELAY)
            if j % 10 == 0:
                save_cache()

        print()
        print("User guide summary:")
        print(f"  Polished     : {guide_polished}")
        print(f"  Unchanged    : {guide_skipped}")
        print(f"  Intros added : {intros_added}")
        print(f"  Skipped (validation failed): {guide_errors}")

    # --- Final cache save + report -------------------------------------------
    save_cache()

    if args.report:
        with open(args.report, "w", encoding="utf-8") as fh:
            json.dump(all_results, fh, indent=2)
        print(f"\nReport saved to: {args.report}")


if __name__ == "__main__":
    main()
