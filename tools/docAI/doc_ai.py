# Custom yaml Dumper: multi-line strings use literal block style (|) so that
# LaTeX sequences like \sigma, \n etc. are never interpreted as YAML escapes.
class _LiteralDumper(yaml.Dumper):
    pass

def _literal_str_representer(dumper, data):
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)

_LiteralDumper.add_representer(str, _literal_str_representer)


def _yaml_dump(data: dict) -> str:
    return yaml.dump(data, Dumper=_LiteralDumper, allow_unicode=True,
                     default_flow_style=False, sort_keys=False, width=120)


