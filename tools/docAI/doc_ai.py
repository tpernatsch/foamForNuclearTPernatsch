def _call_with_retry(fn, *args, **kwargs):
    """
    Call fn(*args, **kwargs) with exponential backoff on 429 rate-limit errors.
    Raises on non-retryable errors or after RETRY_MAX_ATTEMPTS exhausted.
    """
    delay = RETRY_BASE_DELAY
    for attempt in range(1, RETRY_MAX_ATTEMPTS + 1):
        try:
            return fn(*args, **kwargs)
        except Exception as e:
            msg = str(e)
            is_rate_limit = "429" in msg or "Too Many Requests" in msg or "rate_limit" in msg.lower()
            if is_rate_limit and attempt < RETRY_MAX_ATTEMPTS:
                print(f"  [rate limit] waiting {delay:.0f}s before retry {attempt}/{RETRY_MAX_ATTEMPTS - 1}...")
                time.sleep(delay)
                delay *= 2
            else:
                raise


