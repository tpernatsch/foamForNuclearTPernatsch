def _resolve_output_path(original: Path, output_dir: Path | None) -> Path:
    """Return the destination path, mirroring repo structure under output_dir."""
    if output_dir is None:
        return original
    rel = original.relative_to(REPO_ROOT)
    dest = output_dir / rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    return dest


def process_yaml_file(
    client: OpenAI,
    yaml_path: Path,
    mode: str,
    model: str,
    theory_model: str,
    add_theory: bool,
    dry_run: bool,
    force: bool,
    few_shot: str,
    cache: dict,
    verbose: bool,
    progress_paths: frozenset = frozenset(),
    output_dir: Path | None = None,
) -> dict:
    """Process a single yaml file according to the requested mode."""
    result: dict = {"path": str(yaml_path), "action": "none", "error": None}

    try:
        existing_yaml = yaml_path.read_text(encoding="utf-8") if yaml_path.exists() else ""
        incomplete = is_incomplete(yaml_path, progress_paths)

        will_generate = mode in ("generate", "all") and (incomplete or force)
        will_check = mode in ("check", "all") and not incomplete

        content_hash = hashlib.md5(existing_yaml.encode()).hexdigest()[:8]
        chk_key = f"check_v4|{yaml_path}|{model}|{content_hash}"
        check_cached = chk_key in cache

        # The generate cache key hashes the source context, so sources must be
        # read up-front when generating; for check-only, skip reads on cache hit.
        needs_source = will_generate or (will_check and not check_cached)
        source_info = find_source_files(yaml_path) if needs_source else {"class_name": yaml_path.stem}

        generate_cached = False
        if will_generate:
            src_ctx = build_source_context(source_info)
            ctx_hash = hashlib.md5((existing_yaml + src_ctx).encode()).hexdigest()[:8]
            gen_key = f"generate_v2|{yaml_path}|{model}|{theory_model}|{add_theory}|{ctx_hash}"
            generate_cached = gen_key in cache

        # Report from_cache accurately: True only when the operation that will
        # actually run is already cached (not just any operation).
        if will_generate:
            result["from_cache"] = generate_cached
        elif will_check:
            result["from_cache"] = check_cached
        else:
            result["from_cache"] = False

        # ---- Generate mode (incomplete files) --------------------------------
        if mode in ("generate", "all") and (incomplete or force):
            # Determine up-front whether this stub already has content worth
            # preserving.  Files with INCOMPLETE_MARKER are auto-generated stubs
            # whose usage should be replaced by tutorial snippets if any exist.
            has_incomplete_marker = INCOMPLETE_MARKER in existing_yaml
            try:
                orig = yaml.safe_load(existing_yaml) or {}
                orig_desc = str(orig.get("description") or "").strip()
                stub_had_content = (
                    len(orig_desc) > 80
                    or bool(orig.get("usage"))
                    or bool(orig.get("options"))
                    or bool(orig.get("externalOptions"))
                )
            except Exception:
                stub_had_content = False

            # Always search for tutorial snippets when the file is marked as
            # auto-generated (INCOMPLETE_MARKER present), even if it already
            # has a usage field — that field may itself be auto-generated.
            tutorial_snippets: list[str] | None = None
            if (not stub_had_content or has_incomplete_marker) and not generate_cached:
                class_name = source_info.get("class_name") or yaml_path.stem
                tutorial_snippets = find_tutorial_usage(class_name, REPO_ROOT)

            new_yaml = generate_yaml(
                client, yaml_path, source_info, existing_yaml,
                few_shot, model, theory_model, add_theory, cache,
                tutorial_snippets=tutorial_snippets,
            )
            # Safety net: restore original usage, non-warning admonitions,
            # and embedded toctree directives if the LLM wiped them.
            # Exception: do NOT restore usage when INCOMPLETE_MARKER was present
            # (the old usage was auto-generated and should be superseded).
            if stub_had_content:
                try:
                    orig_data = yaml.safe_load(existing_yaml) or {}
                    new_data = yaml.safe_load(new_yaml) or {}
                    restored = False
                    if (orig_data.get("usage") and not new_data.get("usage")
                            and not has_incomplete_marker):
                        new_data["usage"] = orig_data["usage"]
                        restored = True
                    orig_adm = [a for a in (orig_data.get("admonitions") or [])
                                if INCOMPLETE_MARKER not in str(a.get("body", ""))]
                    new_adm = [a for a in (new_data.get("admonitions") or [])
                               if INCOMPLETE_MARKER not in str(a.get("body", ""))]
                    if orig_adm and not new_adm:
                        new_data["admonitions"] = orig_adm
                        restored = True
                    # Restore human-written options the LLM dropped from the
                    # stub (a truncated source excerpt is not evidence of
                    # absence — same protection the check path already has).
                    if _restore_dropped_options(orig_data, new_data):
                        restored = True
                    # Preserve toctree directives embedded in the description
                    orig_desc_str = str(orig_data.get("description") or "")
                    new_desc_str = str(new_data.get("description") or "")
                    fixed_desc = _preserve_description_toctrees(orig_desc_str, new_desc_str)
                    if fixed_desc != new_desc_str:
                        new_data["description"] = fixed_desc
                        restored = True
                    if restored:
                        new_yaml = _yaml_dump(new_data)
                except Exception:
                    pass
            if stub_had_content:
                changed = _changed_sections(existing_yaml, new_yaml)
                new_yaml = _set_ai_provenance(new_yaml, model, modified_sections=changed, stub_improved=True)
            else:
                new_yaml = _set_ai_provenance(new_yaml, model, generated=True)
            result["action"] = "generated"
            result["new_content"] = new_yaml
            if not dry_run and new_yaml != existing_yaml:
                _resolve_output_path(yaml_path, output_dir).write_text(new_yaml, encoding="utf-8")

        # ---- Check mode (complete files) --------------------------------------
        elif mode in ("check", "all") and not incomplete:
            needs_update, updated = check_consistency(
                client, yaml_path, source_info, existing_yaml, model, cache
            )
            if needs_update:
                changed = _changed_sections(existing_yaml, updated)
                updated = _set_ai_provenance(updated, model, modified_sections=changed)
                result["action"] = "consistency-updated"
                result["new_content"] = updated
                if not dry_run:
                    _resolve_output_path(yaml_path, output_dir).write_text(updated, encoding="utf-8")
                existing_yaml = updated  # chain into formulation step
                # Pre-populate cache for the new content so a subsequent run
                # recognises the updated file as already-checked and skips it.
                new_hash = hashlib.md5(updated.encode()).hexdigest()[:8]
                cache[f"check_v4|{yaml_path}|{model}|{new_hash}"] = {
                    "needs_update": False, "yaml": updated
                }

            # ---- Add missing formulation sections ----------------------------
            if add_theory and mode in ("check", "all"):
                was_added, with_formulation = add_formulation_if_missing(
                    client, yaml_path, source_info, existing_yaml, theory_model, cache
                )
                if was_added:
                    with_formulation = _set_ai_provenance(
                        with_formulation, theory_model, formulation_added=True
                    )
                    result["action"] = result.get("action", "none") + "+formulation"
                    result["new_content"] = with_formulation
                    existing_yaml = with_formulation
                    if not dry_run:
                        _resolve_output_path(yaml_path, output_dir).write_text(with_formulation, encoding="utf-8")

            # ---- Extend short formulation sections ---------------------------
            if add_theory and mode in ("check", "all"):
                was_extended, with_extended = extend_formulation_if_short(
                    client, yaml_path, source_info, existing_yaml, theory_model, cache
                )
                if was_extended:
                    with_extended = _set_ai_provenance(
                        with_extended, theory_model, formulation_extended=True
                    )
                    result["action"] = result.get("action", "none") + "+formulation-extended"
                    result["new_content"] = with_extended
                    if not dry_run:
                        _resolve_output_path(yaml_path, output_dir).write_text(with_extended, encoding="utf-8")

    except Exception as exc:
        result["error"] = str(exc)
        if verbose:
            print(f"    ERROR: {exc}")

    # Attach any source-content flag raised during generate/check
    flag = cache.get(f"source_flag|{yaml_path}")
    if flag:
        result["source_flag"] = flag

    return result


