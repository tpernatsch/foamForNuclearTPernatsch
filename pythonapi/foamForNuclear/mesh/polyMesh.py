    def export_to_openfoam(self):
        Mesh.export_to_openfoam(self)

        path = f"constant/{self.region}/polyMesh"

        # If overwrite is true, remove the current polyMesh
        if (self.isOverwrite):
            try:
                shutil.rmtree(path)
            except:
                pass

        # Duplicate a mesh from elsewhere if the path doesn't exist
        if (not os.path.isdir(path) and self.srcpath is not None):
            copyFolder(self.srcpath, path)

        # Create the mesh
        else:
            os.mkdir(path)

            self.createPointsFile(pointsList=self.pointsList)
            self.createFacesFile(faceList=self.faceList)
            self.createOwnerFile(ownerList=self.ownerList)
            self.createNeighbourFile(neighbourList=self.neighbourList)
            self.createBoundaryFile(boundaryList=self.boundaryList)
            self.createCellZonesFile(cellZonesList=self.cellZonesList)
            self.createFaceZonesFile(faceZonesList=self.faceZonesList)
            # if (not self.baffleSet.is_empty):
            #     self.createFaceSet(faceSetName="baffleSet", faceSet=self.baffleSet)


    def plot_voronoi_cells(self):
        rng = np.random.default_rng(11)

        fig = plt.figure()
        ax = fig.add_subplot(111, projection='3d')

        # for each Voronoi cell, plot all the faces of the corresponding polygon
        for vnoicell in self.voronoiGraph:
            faces = []
            # the vertices are the corner points of the Voronoi cell
            vertices = np.array(vnoicell['vertices'])
            # cycle through all faces of the polygon
            for face in vnoicell['faces']:
                faces.append(vertices[np.array(face['vertices'])])

            # join the faces into a 3D polygon
            polygon = Poly3DCollection(
                faces,
                alpha=0.5,
                facecolors=rng.uniform(0,1,3),
                linewidths=0.5,
                edgecolors='black'
            )
            ax.add_collection3d(polygon)

        return(fig, ax)
